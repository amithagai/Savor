export function normalizeSizeGuideContent(content?: Partial<SizeGuideContent> | null): SizeGuideContent {
  return {
    ...DEFAULT_SIZE_GUIDE_CONTENT,
    ...content,
    steps: Array.isArray(content?.steps)
      ? content.steps.map((step, index) => ({
          id: step.id || `step-${index + 1}`,
          title: step.title || '',
          lead: step.lead || '',
          body: step.body || '',
          note: step.note || '',
        }))
      : DEFAULT_SIZE_GUIDE_CONTENT.steps,
  }
}
